"""Reporte markdown de una corrida (scorecard + por familia + por caso)."""

from __future__ import annotations


def _fmt(v) -> str:
    return "n/a" if v is None else str(round(v))


def build_report(results: dict) -> str:
    model = results["model"]
    agg = results["aggregate"]
    cases = results["cases"]

    n_err = results.get("n_errored", 0)
    lines: list[str] = [f"# FHIR Agent Benchmark — Results\n",
                        f"**Model:** `{model}`  ",
                        f"**Cases scored:** {agg.get('n_cases', 0)}"
                        + (f" · **errored:** {n_err}" if n_err else "") + "\n"]
    if n_err:
        lines.append(f"> ⚠️ {n_err} case(s) failed to run (excluded from scores). "
                     "See the By case table.\n")

    # Scorecard principal.
    lines.append("## Scorecard\n")
    lines.append("| Dimension | Score |")
    lines.append("|-----------|------:|")
    for dim, label in (("CC", "Clinical Correctness"), ("FV", "FHIR Validity"),
                       ("SF", "Safety"), ("TRC", "Traceability"),
                       ("SR", "Serialization Robustness")):
        gate = " ⚠ gate" if dim == "SF" else ""
        lines.append(f"| {label} | {_fmt(agg.get(dim))}{gate} |")
    lines.append(f"| **Overall** | **{_fmt(agg.get('overall'))}** |")

    # Por familia.
    lines.append("\n## By family\n")
    lines.append("| Family | Cases | CC | FV | SF | TRC | SR | Overall |")
    lines.append("|--------|------:|---:|---:|---:|----:|---:|--------:|")
    for fam, d in sorted(agg.get("per_family", {}).items()):
        lines.append(
            f"| {fam} | {d['n_cases']} | {_fmt(d['CC'])} | {_fmt(d['FV'])} | "
            f"{_fmt(d['SF'])} | {_fmt(d['TRC'])} | {_fmt(d['SR'])} | {_fmt(d['overall'])} |"
        )

    # Por caso.
    lines.append("\n## By case\n")
    lines.append("| Case | Capability | CC | SF | TRC | SR | Overall |")
    lines.append("|------|------------|---:|---:|----:|---:|--------:|")
    for c in cases:
        overall = "ERR" if c.get("error") else c.get("overall")
        lines.append(
            f"| {c.get('case_id')} | {c.get('capability_id')} | {_fmt(c.get('CC'))} | "
            f"{_fmt(c.get('SF'))} | {_fmt(c.get('TRC'))} | {_fmt(c.get('SR'))} | "
            f"{overall} |"
        )

    lines.append("\n---\n_Generated by the FHIR Agent Benchmark runner. "
                 "Safety gates the overall score; an uncaught critical safety event caps it._\n")
    return "\n".join(lines)
